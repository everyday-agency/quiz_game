import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const batch=Number(process.env.BATCH||1),pad=String(batch).padStart(2,'0');
// Refuse stale or repeated acceptance before running checks or writing any snapshot.
const state=JSON.parse(readFileSync('laravel-specialist/WORK_STATE.json'));
assert.equal(state.nextBatch,batch,'Sequential acceptance required; accepted snapshots cannot be overwritten');
assert(!existsSync('laravel-specialist/batches/batch-'+pad+'.json'),'Accepted batch already exists');
execFileSync(process.execPath,['tools/laravel-specialist-check.mjs'],{stdio:'inherit',env:{...process.env,BATCH:String(batch)}});
const qs=(await import(`../laravel-specialist/authoring/batch-${pad}.mjs`)).default;
const hash=v=>createHash('sha256').update(JSON.stringify(v)).digest('hex');
const read=p=>JSON.parse(readFileSync(p));
const write=(p,x)=>writeFileSync(p,JSON.stringify(x,null,2)+'\n');
const review=read(`laravel-specialist/reviews/batch-${pad}.json`);
assert.equal(review.sourceHash,hash(qs));assert.equal(review.completed,true);
assert.equal(review.independentApproval,'pending');assert.equal(review.itemReviews.length,100);
assert.deepEqual(review.itemReviews.map(x=>[x.id,x.revision]),qs.map(q=>[q.id,q.revision]));
for(const q of qs)if(q.revision>1)assert(existsSync(`laravel-specialist/archive/revisions/${q.id}-r${q.revision-1}.json`),'Prior revision missing');
const accepted=qs.map(q=>({...q,status:'internal-validated',validation:{...q.validation,status:q.validation.kind==='runtime'?'runtime-verified':'documented-contract-reviewed',independentEditorialReview:'pending',evidence:`laravel-specialist/evidence/batch-${batch}-technical.json`}}));
write(`laravel-specialist/batches/batch-${pad}.json`,accepted);
const mapPath='laravel-specialist/curriculum-mappings.json';
const mapping=existsSync(mapPath)?read(mapPath):{revision:1,outline:'working completed Lessons 1-8; no future numbers',questions:{}};
for(const q of accepted)mapping.questions[q.id]={lessonIds:q.curriculum.lessonIds,coverageComplete:q.curriculum.coverageComplete};
write(mapPath,mapping);
state.batches[batch-1]={...state.batches[batch-1],status:'internally-accepted',sourceHash:hash(qs),acceptedHash:hash(accepted),count:100,independentApproval:'pending'};
state.accepted=batch*100;state.nextBatch=batch<6?batch+1:null;
state.phase=batch<6?`batch-${batch+1}-planning`:'final-internal-editorial-audit';
state.next=batch<6?`Plan 100 distinct objectives for batch ${batch+1}, comparing all accepted objectives first.`:'Review all 600 across batches; build local review collection and run regressions/browser tests.';
write('laravel-specialist/WORK_STATE.json',state);
console.log(`Batch ${batch} saved: ${accepted.length} internally validated; independent approval pending. Nothing activated.`);
